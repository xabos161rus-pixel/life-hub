/** Метрика иконок приложения.
 *
 *  ШТРИХ. lucide рисует в системе координат 24×24, поэтому атрибут
 *  stroke-width — не пиксели, а доли этой сетки: один и тот же вес 1.75 даёт
 *  1.02px настоящего штриха при size=14 и 2.92px при size=40. Разброс почти
 *  втрое — мелкие иконки выглядели блёклыми, крупные жирными. Раньше это
 *  значение стояло в CSS одной строкой на всех (.lucide{stroke-width:1.75}) и
 *  вдобавок молча перебивало любой strokeWidth в разметке: двенадцать таких
 *  мест в коде не действовали вообще.
 *
 *  Теперь провайдер в App.tsx включает absoluteStrokeWidth, и lucide сам делит
 *  вес на размер. Следствие: значения ниже и любой strokeWidth в разметке —
 *  это ПИКСЕЛИ готового штриха, одинаковые при любом размере иконки.
 *
 *  РАЗМЕРЫ. Пять ступеней, каждая со своей ролью, плюс дисплейная группа для
 *  заглушек и обложек. Двадцати произвольных значений быть не должно: рядом
 *  стоящие 17 и 18 глазом не различить, а вместе они читаются как небрежность.
 */

/** Обычный вес. Совпадает с тем, что раньше получалось на самой частой
 *  ступени (20px при 1.75), — основная масса иконок веса не изменила. */
export const STROKE = 1.5;

/** Акцент: активная вкладка, кнопка тулбара, дисплейная иконка в заглушке.
 *  Разница с обычным должна читаться без сравнения бок о бок — 1.5 → 2.0 на
 *  глаз заметна, 1.5 → 1.75 уже нет. */
export const STROKE_STRONG = 2;

/** Глиф поверх плотной заливки: галочка в закрашенном квадрате, «плюс» на
 *  градиенте. На заливке тонкий штрих съедается ореолом сглаживания. */
export const STROKE_HEAVY = 2.4;

/** Ступени размера.
 *  inline  — значок внутри строки текста: бейдж, метка, подпись
 *  action  — действие внутри строки списка
 *  base    — основная: шиты, ряды, кнопки действий
 *  header  — шапка экрана, настройки, шевроны
 *  accent  — акцентное действие: плавающая кнопка, плеер, звонок
 *  display — заглушка пустого списка, обложка, вводный экран
 *
 *  hero    — вводный экран, аватар-заглушка, кнопка плеера: там иконка и есть
 *            содержимое экрана, а не пометка рядом с текстом
 *
 *  Иконка в цветной плитке занимает 0.47 её стороны: меньше — глиф тонет в
 *  подложке, больше — упирается в скругление. Замерено по всем экранам
 *  (scratchpad/icon-tiles.mjs), 32 плитки из 34 держат ровно это отношение.
 *
 *  Два исключения намеренные и плиткой не являются:
 *    · плавающая кнопка «+» — 24 в круге 56px (0.43). Это платформенное
 *      соотношение FAB, менять его значило бы спорить с привычкой пальца;
 *    · заглушка аватара — силуэт вместо фотографии, а не значок. В iOS он
 *      тоже стоит с большим полем вокруг. */
export const ICON = {
  inline: 14,
  action: 16,
  base: 18,
  header: 20,
  accent: 24,
  display: 32,
  hero: 40,
} as const;
