// Собственные глифы приложения.
//
// ЗАЧЕМ. lucide рисует «инженерно»: много мелких деталей, разная оптическая
// плотность у соседних иконок, узнаваемость держится на подробностях. На
// экране телефона это читается как шум — солнце с восемью лучами, блокнот со
// спиралью и тремя полосками, батарея в квадратных скобках. Набор ниже
// нарисован по правилам, по которым сделаны SF Symbols: крупная форма, мало
// элементов, силуэт узнаётся с одного взгляда и на 14px.
//
// ПРАВИЛА НАБОРА
//  · сетка 24×24, поле 2px по краям — глиф живёт в квадрате 20×20;
//  · толщину штриха НЕ задаём: её ставит LucideProvider в App.tsx, и в
//    пикселях (ui/icons.ts). Поэтому здесь только геометрия;
//  · концы и стыки скруглены (stroke-linecap/linejoin — из defaultAttributes);
//  · радиус скруглений 2 у мелких форм, 3-4 у крупных: один радиус на весь
//    набор выглядит либо колюче, либо мыльно;
//  · окружности предпочитаем многоугольникам, симметрию — асимметрии;
//  · ничего мельче 2 единиц сетки: на 14px такая деталь схлопывается в пятно.
//
// СОВМЕСТИМОСТЬ. Компоненты принимают тот же набор пропов, что иконки lucide
// (size, strokeWidth, className, fill), и объявлены как LucideIcon — поэтому
// подставляются в IconButton, EmptyState, реестр разделов и таб-бар без единой
// правки на местах вызова.
//
// ГРАНИЦА. Перерисовано то, что человек видит постоянно: таб-бар, плитки
// разделов, панель форматирования, частые действия. Редкие иконки в глубине
// настроек остаются на lucide — они совместимы по метрике (та же сетка 24, те
// же скруглённые концы, тот же вес), и разница в подробности рисунка там
// никому не мешает. Честно: смесь двух наборов заметна, если положить рядом
// два экрана; поштучная дорисовка остальных ста — работа на отдельный заход.

import { forwardRef, type SVGProps } from 'react';
import { useLucideContext, type LucideIcon } from 'lucide-react';
import { STROKE } from './icons';

interface GlyphProps extends Omit<SVGProps<SVGSVGElement>, 'ref'> {
  size?: number | string;
  strokeWidth?: number | string;
  absoluteStrokeWidth?: boolean;
}

/** Обёртка: повторяет контракт иконки lucide, включая класс .lucide, по
 *  которому тесты метрики находят все глифы приложения. */
function glyph(name: string, draw: React.ReactNode): LucideIcon {
  const C = forwardRef<SVGSVGElement, GlyphProps>(
    ({ size = 24, strokeWidth, className = '', absoluteStrokeWidth, ...rest }, ref) => {
      // Вес берём из того же контекста, что и иконки lucide, — иначе набор
      // разъезжается по толщине с соседями. Он же и единственный источник:
      // провайдер стоит в App.tsx, значения в ui/icons.ts.
      //
      // Без этого strokeWidth оставался undefined, SVG подставлял свой
      // дефолт 1, и на мелких размерах штрих выходил 0.58px вместо 1.5 —
      // ровно то расхождение, ради которого метрику и заводили. Поймал тест
      // e2e/icons.spec.ts, а не глаз.
      const ctx = useLucideContext() ?? {};
      const absolute = absoluteStrokeWidth ?? ctx.absoluteStrokeWidth ?? false;
      const weight = Number(strokeWidth ?? ctx.strokeWidth ?? STROKE);
      const sw = absolute ? (weight * 24) / Number(size) : weight;
      return (
        <svg
          ref={ref}
          xmlns="http://www.w3.org/2000/svg"
          width={size}
          height={size}
          viewBox="0 0 24 24"
          fill="none"
          stroke="currentColor"
          strokeWidth={sw}
          strokeLinecap="round"
          strokeLinejoin="round"
          aria-hidden="true"
          className={`lucide lucide-${name} ${className}`.trim()}
          {...rest}
        >
          {draw}
        </svg>
      );
    },
  );
  C.displayName = name;
  return C as unknown as LucideIcon;
}

