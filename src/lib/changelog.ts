/** Короткий текст для push-уведомления.
 *
 *  Ограничение в 140 символов — со стороны воркера, он режет по этой границе
 *  без разбора. Обрывать на полуслове нельзя: уведомление и так короткое, а
 *  оборванная фраза читается как сбой. Поэтому набираем пункты целиком, пока
 *  влезают; если не влезает даже первый — режем его по границе слова и ставим
 *  многоточие, чтобы обрыв выглядел намеренным. */
export function pushTextFor(release: Release, limit = 140): string {
  const out: string[] = [];
  for (const item of release.items) {
    if ([...out, item].join('; ').length > limit) break;
    out.push(item);
  }
  if (out.length > 0) return out.join('; ');

  const first = release.items[0] ?? '';
  if (first.length <= limit) return first;
  const cut = first.slice(0, limit - 1);
  const lastSpace = cut.lastIndexOf(' ');
  return (lastSpace > limit / 2 ? cut.slice(0, lastSpace) : cut).trimEnd() + '…';
}
