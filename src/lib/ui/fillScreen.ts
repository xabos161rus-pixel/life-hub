// Признак «на экране открыт раздел во весь рост».
//
// Экраны переписки (семейный чат, чат с ИИ) занимают всю высоту и не
// прокручиваются целиком: у ленты свой скролл, а поле ввода прибито к низу.
// Баннер установки, который на обычных страницах спокойно уезжает вместе с
// лентой, здесь уезжать некуда — он просто отнимал у чата полтора десятка
// процентов высоты, а вместе с остальными плашками выталкивал поле ввода
// за нижний край экрана: написать сообщение было нельзя вовсе.
//
// Список маршрутов в баннере был бы хрупким — про него забыли бы при
// добавлении третьего такого экрана. Поэтому экран сам заявляет о себе, пока
// открыт, а баннер просто уступает ему место.

let open = 0;
const subs = new Set<() => void>();

function notify() {
  for (const cb of subs) cb();
}

/** Экран во весь рост открылся. Возвращает функцию «закрылся». */
export function markFillScreen(): () => void {
  open++;
  notify();
  let released = false;
  return () => {
    if (released) return;
    released = true;
    open--;
    notify();
  };
}

export function subscribeFillScreen(cb: () => void): () => void {
  subs.add(cb);
  return () => {
    subs.delete(cb);
  };
}

export function fillScreenOpen(): boolean {
  return open > 0;
}
