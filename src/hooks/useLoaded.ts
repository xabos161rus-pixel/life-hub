// «Данные уже пришли» — против мигания пустого состояния.
//
// useLiveQuery отдаёт undefined, пока Dexie не ответил. Привычка писать
// `?? []` прямо в объявлении склеивает два разных состояния: «грузится» и
// «пусто». В результате на первом кадре рисуется заглушка «пока ничего нет»,
// и человек при каждом открытии экрана видит вспышку пустоты там, где данные
// есть. Хуже всего в чате и статистике, где заглушка занимает весь экран.
//
// Правильный порядок: держать сырое значение, для вычислений подставлять
// пустой массив, а для показа заглушки — сначала спросить, пришло ли вообще.
//
// Пример:
//   const rows = useLiveQuery(() => db.tasks.toArray(), []);
//   const items = rows ?? [];            // считать можно и на пустом
//   if (!useLoaded(rows)) return null;   // а показывать «пусто» — рано
//
// Хук, а не функция, чтобы имя читалось на месте вызова как условие и чтобы
// линтер правил зависимостей видел его как часть рендера.
export function useLoaded(...values: unknown[]): boolean {
  return values.every((v) => v !== undefined);
}
